INSERT INTO tarot_cards (id, code, name_ru, arcana, suit, num)
SELECT 22 + (s.ord - 1) * 14 + r.num,
       s.suit || '_' || lpad(r.num::text, 2, '0'),        -- wands_01 ... pentacles_14
       r.rank_ru || ' ' || s.suit_ru,                     -- "Туз Жезлов"
       'minor',
       s.suit,
       r.num
FROM (VALUES (1, 'wands',     'Жезлов'),
             (2, 'cups',      'Кубков'),
             (3, 'swords',    'Мечей'),
             (4, 'pentacles', 'Пентаклей')) AS s (ord, suit, suit_ru)
CROSS JOIN
     (VALUES ( 1, 'Туз'),      ( 2, 'Двойка'),   ( 3, 'Тройка'),  ( 4, 'Четвёрка'),
